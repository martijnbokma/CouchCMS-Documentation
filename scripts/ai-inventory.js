function isDir(p) {
    try {
        return statSync(p).isDirectory();
    } catch {
        return false;
    }
}

function isFile(p) {
    try {
        return statSync(p).isFile();
    } catch {
        return false;
    }
}

function parseArgs(argv) {
    const out = {
        json: false,
        dryRun: false,
        yes: false,
        remove: [],
        help: false,
        syncExclude: false,
        interactive: false,
    };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === "--json") out.json = true;
        else if (a === "--dry-run") out.dryRun = true;
        else if (a === "--yes" || a === "-y") out.yes = true;
        else if (a === "--interactive" || a === "-i") out.interactive = true;
        else if (a === "--sync-exclude" || a === "--exclude-sync") out.syncExclude = true;
        else if (a === "--remove" || a === "--rm") {
            while (i + 1 < argv.length && !argv[i + 1].startsWith("-")) {
                out.remove.push(argv[++i]);
            }
        } else if (a === "-h" || a === "--help") out.help = true;
    }
    return out;
}

function normalizeRemoveName(name) {
    const t = name.trim();
    if (!t || t.includes("..") || t.includes("/") || t.includes("\\")) {
        return null;
    }
    if (!t.startsWith(".")) {
        return null;
    }
    return t;
}

function entryByPath(name) {
    return ENTRIES.find((e) => e.path === name);
}

function listUnclassifiedDotDirs() {
    let names = [];
    try {
        names = readdirSync(rootDir);
    } catch {
        return [];
    }
    const known = new Set(ENTRIES.map((e) => e.path));
    const skip = new Set([".git"]);
    const out = [];
    for (const name of names) {
        if (!name.startsWith(".") || name === "." || name === "..") continue;
        if (skip.has(name)) continue;
        if (known.has(name)) continue;
        const full = join(rootDir, name);
        if (!isDir(full)) continue;
        out.push(name);
    }
    return out.sort();
}

function buildReport() {
    const dirs = ENTRIES.map((e) => {
        const full = join(rootDir, e.path);
        return {
            ...e,
            present: isDir(full),
            absolutePath: full,
        };
    });
    const files = SYNC_FILES.map((f) => {
        const full = join(rootDir, f.path);
        return { ...f, present: isFile(full) };
    });
    const unclassified = listUnclassifiedDotDirs();
    return { dirs, files, unclassified };
}

