/**
 * @param {{ dryRun: boolean }} opts
 */
async function runInteractiveSession(opts) {
    const report = buildReport();
    const deletable = report.dirs.filter((d) => d.allowDelete && d.present);
    if (deletable.length === 0) {
        console.log("No removable tool directories are present on disk.\n");
        return;
    }
    const sorted = [...deletable].sort((a, b) => a.label.localeCompare(b.label));
    const selected = await checkbox({
        message: "Select folders to remove (arrow keys, space toggles, enter confirms)",
        choices: sorted.map((d) => ({
            name: `${d.label} (${d.path})`,
            value: d.path,
            description: `${d.kind} · ${d.note}`,
        })),
        pageSize: 18,
        required: false,
    });
    if (selected.length === 0) {
        console.log("No folders selected.\n");
        return;
    }
    const ok = await confirm({
        message: opts.dryRun
            ? `Dry-run ${selected.length} folder(s): ${selected.join(", ")}?`
            : `Remove ${selected.length} folder(s): ${selected.join(", ")}?`,
        default: false,
    });
    if (!ok) {
        console.log("Cancelled.\n");
        return;
    }
    const syncIds = selected.map((p) => DIR_TO_SYNC_SKIP_ID[p]).filter(Boolean);
    let syncExclude = false;
    if (syncIds.length > 0) {
        syncExclude = await confirm({
            message: `Add ${syncIds.join(", ")} to ${SYNC_EXCLUDE_FILENAME} so bun run sync does not recreate them?`,
            default: true,
        });
    }
    runRemove(selected, opts.dryRun, true, syncExclude);
}

function runRemove(names, dryRun, yes, syncExclude) {
    if (names.length === 0) {
        console.error("No paths after --remove.");
        process.exit(1);
    }
    if (!dryRun && !yes) {
        console.error("Refusing to remove without --yes (or use --dry-run to preview).");
        process.exit(1);
    }
    const resolved = [];
    for (const raw of names) {
        const name = normalizeRemoveName(raw);
        if (!name) {
            console.error(`Invalid name: ${raw} (use a single root segment like .giga)`);
            process.exit(1);
        }
        const meta = entryByPath(name);
        if (!meta) {
            console.error(`Unknown or not removable via this script: ${name}`);
            console.error("Only registered paths with allowDelete: true can be removed.");
            process.exit(1);
        }
        if (!meta.allowDelete) {
            console.error(`Not allowed to remove ${name} via this script (protected).`);
            process.exit(1);
        }
        const full = join(rootDir, name);
        if (!isDir(full)) {
            console.error(`Not found or not a directory: ${name}`);
            process.exit(1);
        }
        resolved.push({ name, full });
    }
    const syncIds = resolved.map(({ name }) => DIR_TO_SYNC_SKIP_ID[name]).filter(Boolean);
    if (dryRun && syncExclude && syncIds.length > 0) {
        console.log(
            `[dry-run] would append to ${SYNC_EXCLUDE_FILENAME}: skipWrites += ${syncIds.join(", ")}`,
        );
    }
    for (const { name, full } of resolved) {
        const rel = relative(rootDir, full);
        if (rel.startsWith("..") || rel.includes("..")) {
            console.error("Path escape rejected.");
            process.exit(1);
        }
        if (dryRun) {
            console.log(`[dry-run] would remove ${full}`);
        } else {
            rmSync(full, { recursive: true, force: true });
            console.log(`Removed ${name}`);
        }
    }
    if (!dryRun && syncExclude && syncIds.length > 0) {
        const merged = addSkipWrites(rootDir, syncIds);
        console.log(`Updated ${SYNC_EXCLUDE_FILENAME}: skipWrites = ${merged.join(", ")}`);
    }
    if (dryRun) {
        console.log("\nRun again with --yes instead of --dry-run to delete.");
    }
}

async function main() {
    const opts = parseArgs(process.argv.slice(2));
    if (opts.help) {
        printHelp();
        process.exit(0);
    }

    if (opts.interactive) {
        if (opts.json) {
            console.error("Cannot use --json with --interactive.");
            process.exit(1);
        }
        if (opts.remove.length > 0) {
            console.error("Use either --interactive or --remove, not both.");
            process.exit(1);
        }
        if (!process.stdin.isTTY) {
            console.error("Interactive mode requires a terminal (TTY).");
            process.exit(1);
        }
        await runInteractiveSession(opts);
        return;
    }

    const report = buildReport();

    if (opts.remove.length > 0) {
        runRemove(opts.remove, opts.dryRun, opts.yes, opts.syncExclude);
        if (!opts.json && opts.remove.length > 0) {
            console.log("");
        }
    }

    if (opts.json) {
        console.log(
            JSON.stringify(
                {
                    root: rootDir,
                    syncExcludeSkipWrites: [...loadSkipWrites(rootDir)].sort(),
                    dirs: report.dirs.map((d) => ({
                        path: d.path,
                        label: d.label,
                        kind: d.kind,
                        present: d.present,
                        allowDelete: d.allowDelete,
                        note: d.note,
                    })),
                    syncedFiles: report.files,
                    unclassifiedDotDirs: report.unclassified,
                },
                null,
                2,
            ),
        );
    } else if (opts.remove.length === 0) {
        printText(report);
    }
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
